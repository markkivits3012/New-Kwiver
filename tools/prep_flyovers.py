#!/usr/bin/env python3
"""Convert Google Earth Pro Movie Maker recordings into the app's flyover clips.

Drop the raw recordings in data/flyovers_raw/ with the hole number anywhere
in the name ("hole 1.mp4", "Hole 01 - Par 5.mov", "07.mp4" all work), then:

    python tools/prep_flyovers.py
    python tools/prep_flyovers.py --src D:\\earth_movies --ffmpeg C:\\path\\ffmpeg.exe

Writes app/flyovers/hole01.mp4 ... hole18.mp4: H.264, 1100x960 (2x the
550x480 map area on the 5" screen, cropped to fit), no audio, faststart so
Chromium can start playing before the whole file is read.
"""
import argparse
import json
import os
import re
import shutil
import subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "data", "flyovers_raw")
OUT = os.path.join(ROOT, "app", "flyovers")
W, H = 1100, 960
EXTS = (".mp4", ".mov", ".m4v", ".avi", ".wmv", ".webm", ".mkv")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=SRC)
    ap.add_argument("--ffmpeg", default=shutil.which("ffmpeg") or "ffmpeg")
    ap.add_argument("--crf", type=int, default=23, help="lower = better quality, bigger files")
    args = ap.parse_args()

    os.makedirs(OUT, exist_ok=True)
    found = {}
    for name in sorted(os.listdir(args.src)):
        if not name.lower().endswith(EXTS):
            continue
        m = re.search(r"(\d+)", name)
        if not m or not 1 <= int(m.group(1)) <= 18:
            print(f"skip {name}: no hole number 1-18 in the name")
            continue
        no = int(m.group(1))
        if no in found:
            print(f"skip {name}: hole {no} already taken by {found[no]}")
            continue
        found[no] = name
        dst = os.path.join(OUT, f"hole{no:02d}.mp4")
        cmd = [args.ffmpeg, "-y", "-loglevel", "error", "-i", os.path.join(args.src, name),
               "-vf", f"scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H},fps=30",
               "-c:v", "libx264", "-profile:v", "high", "-level", "4.1", "-preset", "slow",
               "-crf", str(args.crf), "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an", dst]
        print(f"hole {no:2d}: {name} -> {os.path.relpath(dst, ROOT)}")
        subprocess.run(cmd, check=True)

    # the app only requests clips listed here (no 404s for holes without one)
    have = sorted(int(f[4:6]) for f in os.listdir(OUT) if re.fullmatch(r"hole\d\d\.mp4", f))
    with open(os.path.join(OUT, "flyovers.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/prep_flyovers.py -- holes that have a flyover clip.\n")
        f.write(f"window.FLYOVERS = {json.dumps(have)};\n")

    missing = [n for n in range(1, 19) if n not in found]
    total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT) if f.endswith(".mp4"))
    print(f"\n{len(found)} clips converted, {total / 1e6:.0f} MB in app/flyovers")
    if missing:
        print("no clip for holes", ", ".join(map(str, missing)), "- those use the 2D flyover")


if __name__ == "__main__":
    main()
