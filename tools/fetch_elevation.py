#!/usr/bin/env python3
"""Download the ground shape for the 3D view, once, on a PC with internet.

    python tools/fetch_elevation.py
    python tools/fetch_elevation.py --course office   # a course in courses/<id>/

Source: USGS 3D Elevation Program (3DEP) bare-earth lidar, public domain.
Two heightmaps line up with the aerial photo layers from fetch_aerial.py
(run that first): a fine one over the course photo (2 m) and a coarse one
under the wide photo (15 m) so the view has hills to the horizon.

Writes app/terrain3d/detail.bin and wide.bin (little-endian uint16,
centimeters above the layer's lowest point, rows north to south) and
app/terrain3d/terrain3d.js with their bounds. Needs Pillow on the PC.
"""
import io
import json
import math
import os
import sys
import urllib.parse
import urllib.request
from array import array

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "server"))
import coursedir  # noqa: E402
OUT = os.path.join(ROOT, "app", "terrain3d")  # set per --course in main()
COURSE = coursedir.DEFAULT
DEM = "https://elevation.nationalmap.gov/arcgis/rest/services/3DEPElevation/ImageServer/exportImage"
R = 6378137.0
LAYERS = {"detail": 2.0, "wide": 15.0}  # meters between height samples


def merc_y(lat):
    return R * math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))


def merc_lat(y):
    return math.degrees(2 * math.atan(math.exp(y / R)) - math.pi / 2)


def photo_bounds():
    with open(coursedir.path(COURSE, "app", "aerial", "aerial.js"), encoding="utf-8") as f:
        text = f.read()
    tiles = json.loads(text[text.index("{"):text.rindex("}") + 1])["tiles"]
    out = {}
    for name in LAYERS:
        ts = [t for t in tiles if t["src"].split("/")[-1].startswith("wide" if name == "wide" else "tile")]
        out[name] = (max(t["north"] for t in ts), min(t["south"] for t in ts),
                     min(t["west"] for t in ts), max(t["east"] for t in ts))
    return out


def fetch(name, bounds, step_m):
    north, south, west, east = bounds
    x0, x1 = R * math.radians(west), R * math.radians(east)
    y0, y1 = merc_y(south), merc_y(north)
    per_px = step_m / math.cos(math.radians((north + south) / 2))  # mercator m per sample
    w, h = round((x1 - x0) / per_px), round((y1 - y0) / per_px)
    q = urllib.parse.urlencode({"bbox": f"{x0},{y0},{x1},{y1}", "bboxSR": 3857, "imageSR": 3857,
                                "size": f"{w},{h}", "format": "tiff", "pixelType": "F32",
                                "interpolation": "RSP_BilinearInterpolation", "f": "image"})
    req = urllib.request.Request(f"{DEM}?{q}", headers={"User-Agent": "tashua-golf-map/0.1"})
    with urllib.request.urlopen(req, timeout=180) as r:
        img = Image.open(io.BytesIO(r.read()))
        img.load()
    w, h = img.size
    z = list(img.get_flattened_data() if hasattr(img, "get_flattened_data") else img.getdata())
    good = [v for v in z if -100 < v < 3000]
    if len(good) < len(z):
        print(f"  {name}: {len(z) - len(good)} missing samples filled with the lowest height")
    zmin = min(good)
    z = [v if -100 < v < 3000 else zmin for v in z]
    cm = array("H", (min(65535, round((v - zmin) * 100)) for v in z))
    if cm.itemsize != 2:
        raise SystemExit("uint16 array isn't 2 bytes on this Python")
    if array("H", [1]).tobytes() != b"\x01\x00":
        cm.byteswap()
    with open(os.path.join(OUT, f"{name}.bin"), "wb") as f:
        cm.tofile(f)
    # sample centers sit half a sample in from the requested edges
    dx, dy = (x1 - x0) / w, (y1 - y0) / h
    meta = {"src": f"terrain3d/{name}.bin", "w": w, "h": h, "zmin": round(zmin, 2), "scale": 0.01,
            "north": merc_lat(y1 - dy / 2), "south": merc_lat(y0 + dy / 2),
            "west": math.degrees((x0 + dx / 2) / R), "east": math.degrees((x1 - dx / 2) / R)}
    print(f"{name}: {w} x {h} samples at {step_m:g} m, ground {zmin:.1f} to {max(z):.1f} m, "
          f"{os.path.getsize(os.path.join(OUT, name + '.bin')) / 1e6:.1f} MB")
    return meta


def main():
    global COURSE, OUT
    import argparse
    ap = argparse.ArgumentParser()
    coursedir.add_arg(ap)
    COURSE = ap.parse_args().course
    OUT = coursedir.path(COURSE, "app", "terrain3d")
    os.makedirs(OUT, exist_ok=True)
    bounds = photo_bounds()
    meta = {"source": "USGS 3D Elevation Program (public domain)",
            **{name: fetch(name, bounds[name], step) for name, step in LAYERS.items()}}
    with open(os.path.join(OUT, "terrain3d.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/fetch_elevation.py -- lidar heightmaps for the 3D view.\n")
        f.write("window.TERRAIN3D = " + json.dumps(meta, indent=1) + ";\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
