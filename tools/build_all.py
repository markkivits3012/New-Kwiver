#!/usr/bin/env python3
"""Build everything for one course, in order, stopping at the first error.

    python tools/build_all.py --course whitney     # a course from tools/new_course.py
    python tools/build_all.py                      # Tashua Knolls

Runs: build_course (or make_test_course for a hand-drawn test course),
fetch_aerial, fetch_elevation, build_terrain --check, build_routes.
Needs internet the first time (OpenStreetMap, NAIP aerials, USGS elevation).
"""
import argparse
import os
import subprocess
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(TOOLS, "..", "server"))
import coursedir  # noqa: E402


def run(script, *args):
    cmd = [sys.executable, os.path.join(TOOLS, script), *args]
    print(f"\n=== {script} {' '.join(args)}", flush=True)
    if subprocess.call(cmd) != 0:
        sys.exit(f"\nSTOPPED: {script} failed (see above). Fix it and run build_all.py again.")


def main():
    ap = argparse.ArgumentParser()
    coursedir.add_arg(ap)
    c = ap.parse_args().course
    course = ["--course", c]

    if os.path.exists(coursedir.path(c, "course-def.json")):
        run("make_test_course.py", *course)
    elif c == coursedir.DEFAULT or os.path.exists(coursedir.path(c, "course.json")):
        run("build_course.py", *course)  # downloads OSM data if there is none yet
    else:
        sys.exit(f"no course {c!r}: run  python tools/new_course.py {c} \"<course name, town state>\"  first")
    fly = coursedir.path(c, "app", "flyovers", "flyovers.js")
    if not os.path.exists(fly):  # no video clips yet: the app plays 2D/3D flyovers
        os.makedirs(os.path.dirname(fly), exist_ok=True)
        with open(fly, "w", encoding="utf-8") as f:
            f.write("// Generated by tools/prep_flyovers.py -- holes that have a flyover clip.\n"
                    "window.FLYOVERS = [];\n")
    run("fetch_aerial.py", *course)
    run("fetch_elevation.py", *course)
    run("build_terrain.py", "--check", *course)
    run("build_routes.py", *course)

    print(f"""
=== done: {c}
Look at:
  1. any WARNING lines from build_course above (holes, greens or tees it could not match)
  2. {coursedir.path(c, "data", "terrain_check.png")}
     (trees, steep ground and buildings the cart must avoid; make sure they look right)
  3. routes marked NO ROUTE or flagged in the build_routes list above
Try it:  python server/gps_server.py --course {c} --sim   then open http://127.0.0.1:8080""")


if __name__ == "__main__":
    main()
